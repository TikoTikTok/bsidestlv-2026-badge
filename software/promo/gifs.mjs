// The README's animations, from the promo's render and the badge art.
//
//   node gifs.mjs svg      images/badge-keys.svg - the badge off the PCB with its buttons lighting in turn (CSS, no script)
//   node gifs.mjs gifs     images/*.gif - cuts of out/promo.mp4 (after `npx hyperframes render`), palette-optimised
//   node gifs.mjs          both
//
// The cut list below names the promo's scenes by their start and end in the
// render; keep it in step with index.html's data-start / data-duration.
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const IMAGES = path.resolve(HERE, '..', '..', 'images');
const RENDER = path.join(HERE, 'out', 'promo.mp4');
const what = process.argv[2] ?? 'all';

// ------------------------------------------------------------- the badge SVG --
function badgeSvg() {
  const raw = fs.readFileSync(path.join(HERE, 'assets', 'badge.svg'), 'utf8');
  const v = JSON.parse(fs.readFileSync(path.join(HERE, 'assets', 'badge-theme.json'), 'utf8'));
  const ORDER = ['UP', 'RIGHT', 'DOWN', 'LEFT', 'X', 'A', 'B', 'Y', 'SR', 'SL', 'START', 'SELECT'];
  const beat = 0.65, period = +(ORDER.length * beat).toFixed(2);
  const pct = (s) => +((s / period) * 100).toFixed(3);
  const mono = 'ui-monospace, SFMono-Regular, Menlo, Consolas, monospace';
  const css = `
    .shell { fill: ${v.well}; stroke: ${v.line}; stroke-width: .5; }
    .hub { fill: ${v['panel-2']}; }
    .key .cap { fill: ${v['panel-2']}; stroke: ${v.line}; stroke-width: .45; }
    .key text { font: 700 3.4px ${mono}; fill: ${v.dim}; text-anchor: middle; dominant-baseline: central; letter-spacing: .02em; }
    .key text.word { font-size: 2.1px; font-weight: 400; letter-spacing: .08em; }
    .key text.tiny { font-size: 1.7px; }
    .key[data-key=SL] text, .key[data-key=SR] text { font-size: 2.6px; }
    .key .glyph { fill: ${v.dim}; }
    .ring { fill: none; stroke: ${v.accent}; stroke-width: .6; opacity: 0; transform-box: fill-box; transform-origin: center; }
    .gauge { display: none; }
    .led { fill: ${v['accent-2']}; opacity: .35; animation: led ${period}s linear infinite; }
    .usb { fill: ${v['ink-2']}; stroke: ${v.line}; stroke-width: .4; }
    @keyframes cap { 0%, ${pct(beat * 0.85)}% { fill: ${v.accent}; stroke: ${v.accent}; } ${pct(beat)}%, 100% { fill: ${v['panel-2']}; stroke: ${v.line}; } }
    @keyframes ink { 0%, ${pct(beat * 0.85)}% { fill: ${v['on-accent']}; } ${pct(beat)}%, 100% { fill: ${v.dim}; } }
    @keyframes word { 0%, ${pct(beat * 0.85)}% { fill: ${v.accent}; } ${pct(beat)}%, 100% { fill: ${v.dim}; } }
    @keyframes ripple { 0% { transform: scale(1); opacity: .9; } ${pct(beat * 1.3)}%, 100% { transform: scale(1.9); opacity: 0; } }
    @keyframes led { 0%, 100% { opacity: .35; } 50% { opacity: 1; } }
    ${ORDER.map((k, i) => {
      const d = `${(i * beat).toFixed(2)}s`;
      return `.key[data-key=${k}] .cap { animation: cap ${period}s linear ${d} infinite; }
    .key[data-key=${k}] text, .key[data-key=${k}] .glyph { animation: ink ${period}s linear ${d} infinite; }
    .key[data-key=${k}] text.word { animation: word ${period}s linear ${d} infinite; }
    .key[data-key=${k}] .ring { animation: ripple ${period}s ease-out ${d} infinite; }`;
    }).join('\n    ')}
  `;
  const svg = raw
    .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
    .replace(/<svg([^>]*)>/, (m, attrs) => `<svg${attrs}>\n  <title>The BSidesTLV 2026 badge as the player holds it: the back of the board, stalk up, each button lighting in turn</title>\n  <style>${css}</style>`);
  const header = `<!-- GENERATED by software/promo/gifs.mjs from software/promo/assets/badge.svg (src/prompt.js over src/badge-shape.js, itself generated from hardware/badge/PhoneController.kicad_pcb). The buttons light in turn by CSS alone, so the picture moves anywhere an <img> does. -->\n`;
  fs.writeFileSync(path.join(IMAGES, 'badge-keys.svg'), header + svg);
  console.log(`badge-keys.svg  ${(header + svg).length} bytes, ${ORDER.length} keys, a ${period}s loop`);
}

// ------------------------------------------------------------------ the GIFs --
// cuts.json: { name, from, to } one range of out/promo.mp4, or { name, segments: [[from, to], ...] } joined; width, fps, colors
const CUTS = JSON.parse(fs.readFileSync(path.join(HERE, 'cuts.json'), 'utf8'));
function gif({ name, from, to, segments, width = 640, fps = 12, colors = 192 }) {
  const dst = path.join(IMAGES, `${name}.gif`);
  const segs = segments ?? [[from, to]];
  const trims = segs.map(([a, b], i) => `[0:v]trim=start=${a}:end=${b},setpts=PTS-STARTPTS[c${i}]`).join(';');
  const cat = segs.map((_, i) => `[c${i}]`).join('') + `concat=n=${segs.length}:v=1:a=0[v]`;
  const fc = `${trims};${cat};[v]fps=${fps},scale=${width}:-2:flags=lanczos,split[s0][s1];[s0]palettegen=max_colors=${colors}:stats_mode=diff[p];[s1][p]paletteuse=dither=bayer:bayer_scale=5:diff_mode=rectangle[out]`;
  const r = spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', RENDER, '-filter_complex', fc, '-map', '[out]', '-loop', '0', dst], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`ffmpeg failed on ${name}`);
  const secs = segs.reduce((s, [a, b]) => s + (b - a), 0);
  console.log(`${name}.gif  ${secs.toFixed(1)}s  ${(fs.statSync(dst).size / 1e6).toFixed(2)} MB`);
}

if (what === 'svg' || what === 'all') badgeSvg();
if (what === 'gifs' || what === 'all') {
  if (!fs.existsSync(RENDER)) throw new Error(`no render at ${RENDER}: npx hyperframes render first`);
  for (const c of CUTS) gif(c);
}
